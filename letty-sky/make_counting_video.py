def text_c(d, xy, txt, sz, fill, stroke=10):
    d.text(xy, txt, font=font(sz), fill=fill, anchor="mm", stroke_width=stroke, stroke_fill=(255, 255, 255))


def ease_pop(x):
    """0->1 with overshoot."""
    if x <= 0:
        return 0.0
    if x >= 1:
        return 1.0
    c = 2.2
    x -= 1
    return 1 + (c + 1) * x ** 3 + c * x ** 2


def paste_scaled(frame, img, cx, cy, scale, rot=0):
    if scale <= 0.02:
        return
    w, h = img.size
    im = img.resize((max(1, int(w * scale)), max(1, int(h * scale))), Image.BILINEAR)
    if rot:
        im = im.rotate(rot, resample=Image.BILINEAR, expand=True)
    frame.paste(im, (int(cx - im.width / 2), int(cy - im.height / 2)), im)


def grid(n):
    """Positions for n objects in the right-hand play area."""
    rows = 1 if n <= 4 else 2
    per = math.ceil(n / rows)
    x0, x1 = 760, 1800
    ys = [470] if rows == 1 else [330, 600]
    pts = []
    for r in range(rows):
        cnt = per if r < rows - 1 else n - per * (rows - 1)
        for i in range(cnt):
            pts.append((x0 + (x1 - x0) * (i + 0.5) / per, ys[r]))
    return pts


def draw_chars(frame, tm, cheer=False):
    for who, cx in (("letty", 230), ("sky", W - 230)):
        bob = math.sin(tm * 3 + (0 if who == "letty" else 1.5)) * 10
        hop = abs(math.sin(tm * 9)) * 40 if cheer else 0
        blink = (tm * 1.0 + (0 if who == "letty" else 0.37)) % 3.7 < 0.12
        img = CHAR[(who, int(bool(talking(who, tm))), int(blink))]
        paste_scaled(frame, img, cx, H - 200 + bob - hop, 1.0)


def render(tm):
    frame = BG.copy()
    for x, y, sc, sp in CLOUDS:
        cx = ((x * W + tm * sp) % (W + 400)) - 200
        paste_scaled(frame, CLOUD, cx, y + 80, sc * 1.6)
    d = ImageDraw.Draw(frame)
    sc = next(s for s in scenes if s["start"] <= tm < s["end"] or s is scenes[-1])

    if sc["kind"] == "intro":
        lt = tm - sc["start"]
        k = ease_pop(lt / 0.6)
        title = Image.new("RGBA", (1500, 420), (0, 0, 0, 0))
        td = ImageDraw.Draw(title)
        td.rounded_rectangle([20, 20, 1480, 400], radius=80, fill=(255, 255, 255, 230), outline=hexrgb("#9d4edd"), width=12)
        td.text((750, 140), "Letty & Sky", font=font(150), fill=hexrgb("#9d4edd"), anchor="mm")
        colors = ["#ff4d6d", "#ffd60a", "#38b000"]
        td.text((560, 300), "Learn", font=font(130), fill=hexrgb("#00b4d8"), anchor="mm")
        for i, ch in enumerate("123"):
            td.text((880 + i * 110, 300 + math.sin(tm * 5 + i) * 12), ch, font=font(140), fill=hexrgb(colors[i]), anchor="mm")
        paste_scaled(frame, title, W / 2, 360, k)
        draw_chars(frame, tm)

    elif sc["kind"] == "count":
        n = sc["n"]
        lt = tm - sc["numeral_at"]
        k = ease_pop(lt / 0.5)
        cheering = tm >= sc["cheer_at"]
        # numeral card
        card = Image.new("RGBA", (520, 640), (0, 0, 0, 0))
        cd = ImageDraw.Draw(card)
        cd.rounded_rectangle([10, 10, 510, 630], radius=70, fill=(255, 255, 255, 255), outline=hexrgb(NUM_COLORS[n]), width=14)
        cd.text((260, 280), str(n), font=font(380 if n < 10 else 300), fill=hexrgb(NUM_COLORS[n]), anchor="mm",
                stroke_width=8, stroke_fill=OUTL)
        cd.text((260, 545), WORDS[n].upper(), font=font(96), fill=OUTL, anchor="mm")
        wob = math.sin(tm * 8) * 4 if cheering else 0
        paste_scaled(frame, card, 360, 400, k, wob)
        # objects
        pts = grid(n)
        count_now = sum(1 for p in sc["pops"] if tm >= p)
        scale0 = 1.0 if n <= 4 else 0.85
        for i, (px, py) in enumerate(pts):
            pt = sc["pops"][i]
            if tm < pt:
                continue
            s = ease_pop((tm - pt) / 0.35) * scale0
            yb = 0
            if i == count_now - 1 and not cheering:
                yb = -abs(math.sin((tm - pt) * 6)) * 25 * max(0, 1 - (tm - pt))
            if cheering:
                yb = -abs(math.sin((tm - sc["cheer_at"]) * 7 + i * 0.6)) * 30
            paste_scaled(frame, SHADOW[n], px + 8, py + 14, s)
            paste_scaled(frame, SPR[n], px, py + yb, s)
            # little number tag under each counted object
            tag_k = ease_pop((tm - pt - 0.1) / 0.3)
            if tag_k > 0.05:
                text_c(d, (px, py + OBJ * scale0 / 2 + 30), str(i + 1), int(56 * tag_k) + 1, hexrgb(NUM_COLORS[n]), 6)
        # counter at top
        if count_now and not cheering:
            text_c(d, (1280, 110), f"{count_now}", 110, hexrgb(NUM_COLORS[n]))
        if cheering:
            noun = THINGS[n][0] if n == 1 else THINGS[n][1]
            k2 = ease_pop((tm - sc["cheer_at"]) / 0.4)
            if k2 > 0.05:
                text_c(d, (1280, 110), f"{n} {noun}!".upper(), int(100 * k2) + 1, hexrgb(NUM_COLORS[n]))
        draw_chars(frame, tm, cheer=cheering)

    else:  # recap
        hits = sc["hits"]
        for i in range(10):
            if tm < hits[i]:
                continue
            s = ease_pop((tm - hits[i]) / 0.35)
            x = 260 + (i % 5) * 350
            y = 260 + (i // 5) * 300
            active = i < 9 and hits[i] <= tm < hits[i + 1] or (i == 9 and hits[9] <= tm < hits[9] + 0.6)
            bump = 1.25 if active else 1.0
            r = int(115 * s * bump)
            E(d, x, y, r, r, fill=hexrgb(NUM_COLORS[i + 1]), outline=(255, 255, 255), width=10)
            text_c(d, (x, y), str(i + 1), max(1, int(140 * s * bump)), (255, 255, 255), 0)
        done = tm >= hits[-1] + 0.9
        draw_chars(frame, tm, cheer=done)
        if done:
            k = ease_pop((tm - hits[-1] - 0.9) / 0.5)
            text_c(d, (W / 2, 860), "GREAT JOB!", max(1, int(130 * k)), hexrgb("#f72585"))
    return frame


