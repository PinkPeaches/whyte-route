def talking(who, tm):
    for start, clip, w in speech:
        if w == who and start <= tm < start + len(clip) / SR:
            # open/close mouth with speech envelope
            i = int((tm - start) * SR)
            seg = clip[i: i + 1500]
            return len(seg) and np.abs(seg).mean() > 0.04
    return False

