def tts(text, who):
    """Render a line with espeak-ng; Letty = higher voice, Sky = lower."""
    path = os.path.join(TMP, f"tts_{abs(hash((text, who)))}.wav")
    if not os.path.exists(path):
        voice, pitch = ("en-us+f3", "70") if who == "letty" else ("en-us+m3", "55")
        subprocess.run(["espeak-ng", "-v", voice, "-s", "130", "-p", pitch,
                        "-g", "2", "-w", path, text], check=True)
    with wave.open(path) as w:
        sr = w.getframerate()
        a = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
    # resample to SR
    n = int(len(a) * SR / sr)
    a = np.interp(np.linspace(0, len(a) - 1, n), np.arange(len(a)), a)
    # trim silence
    idx = np.where(np.abs(a) > 0.01)[0]
    if len(idx):
        a = a[max(0, idx[0] - 200): idx[-1] + 800]
    return a * 0.9


def pop_sfx():
    t = np.linspace(0, 0.12, int(SR * 0.12), endpoint=False)
    f = 500 + 1400 * t / 0.12
    return 0.35 * np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 30)


def chime_sfx():
    t = np.linspace(0, 0.9, int(SR * 0.9), endpoint=False)
    out = np.zeros_like(t)
    for i, f in enumerate([1046.5, 1318.5, 1568.0, 2093.0]):
        st = int(i * 0.08 * SR)
        tt = t[: len(t) - st]
        out[st:] += 0.12 * np.sin(2 * np.pi * f * tt) * np.exp(-tt * 5)
    return out


def music(duration):
    """Original cheerful loop: I-V-vi-IV in C major, 112 bpm."""
    bpm = 112
    beat = 60 / bpm
    n = int(duration * SR)
    out = np.zeros(n)

    def note(freq, start, length, vol, shape="sine"):
        s = int(start * SR)
        if s >= n:
            return
        L = min(int(length * SR), n - s)
        t = np.arange(L) / SR
        if shape == "sine":
            w = np.sin(2 * np.pi * freq * t) + 0.3 * np.sin(4 * np.pi * freq * t)
        else:  # soft square-ish (pluck)
            w = np.tanh(3 * np.sin(2 * np.pi * freq * t)) * 0.6
        env = np.minimum(1, t / 0.01) * np.exp(-t * 3.0)
        out[s: s + L] += vol * w * env

    hz = lambda m: 440 * 2 ** ((m - 69) / 12)
    chords = [[60, 64, 67], [55, 59, 62], [57, 60, 64], [53, 57, 60]]  # C G Am F
    # an original 4-bar melody (MIDI note, beats)
    melody = [(72, 1), (76, 1), (79, 1), (76, 1),
              (74, 1), (71, 1), (74, 2),
              (72, 1), (76, 1), (81, 1), (79, 1),
              (77, 1), (76, 1), (74, 2)]
    bar = 4 * beat
    loop = 4 * bar
    t0 = 0.0
    while t0 < duration:
        for b, ch in enumerate(chords):
            bs = t0 + b * bar
            note(hz(ch[0] - 24), bs, bar, 0.18)            # bass
            note(hz(ch[0] - 24), bs + 2 * beat, bar / 2, 0.12)
            for k in range(4):                               # bouncy chords
                for m in ch:
                    note(hz(m), bs + k * beat + beat / 2, beat / 2, 0.035, "pluck")
        mt = t0
        for m, L in melody:
            note(hz(m), mt, L * beat * 0.95, 0.07)
            mt += L * beat
        # light shaker on every 8th note
        for k in range(32):
            s = int((t0 + k * beat / 2) * SR)
            if s < n:
                L = min(int(0.04 * SR), n - s)
                out[s: s + L] += np.random.uniform(-1, 1, L) * 0.025 * np.exp(-np.arange(L) / SR * 80)
        t0 += loop
    fade = int(1.5 * SR)
    out[-fade:] *= np.linspace(1, 0, fade)
    return out

